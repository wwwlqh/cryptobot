"""Withdraw a strategy wallet's realized PnL through the Polymarket relayer.

  * ``preview_transfer(amount_usd, source_wallet_id)`` writes a short-lived
    PREVIEW row carrying an idempotency key and returns a
    ``TransferPreview`` for the dashboard to confirm. Refuses an amount above
    the source wallet's extractable PnL.
  * ``submit_transfer(idempotency_key)`` binds the confirmation to that
    preview, checks ``(amount, to_wallet, source_wallet_id)`` still match
    (``preview_mismatch`` otherwise), then moves to SUBMITTING and enters
    TRANSFER_LOCK.
  * A partial unique index on ``transfer_requests`` allows one SUBMITTING
    row per ``from_wallet``; a concurrent submit hits ``IntegrityError``,
    reported as ``transfer_in_progress``.

The relayer client is injected (production wraps Polymarket's relayer, tests
pass a stub). The flow is idempotent: re-submitting a CONFIRMED key does
nothing.
"""

from __future__ import annotations

import json
import logging
import secrets
import sqlite3
from concurrent.futures import (
    ThreadPoolExecutor,
    TimeoutError as FuturesTimeoutError,
)
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from typing import Any, Callable, Optional

from cryptobot.db.connection import utc_now_sql
from cryptobot.execution.capital import (
    extractable_pnl_for_wallet,
)
from cryptobot.execution.operator_control import (
    LIVE,
    OperatorControlError,
    clear_transfer_lock,
    enter_transfer_lock,
    get_operator_state,
)


# Bound every relayer call so a hung relayer cannot hold PostRouter._lock,
# which serializes every dashboard write endpoint. One shared pool rather than
# an executor per call.
_RELAYER_EXECUTOR = ThreadPoolExecutor(
    max_workers=4, thread_name_prefix="cryptobot-relayer"
)
RELAYER_TIMEOUT_S = 30.0


def _call_relayer_with_timeout(
    relayer_submitter: Callable[[dict[str, Any]], dict[str, Any]],
    payload: dict[str, Any],
    *,
    timeout_s: Optional[float] = None,
) -> dict[str, Any]:
    # Read the timeout at call time so tests can monkeypatch
    # ``RELAYER_TIMEOUT_S``.
    effective_timeout = timeout_s if timeout_s is not None else RELAYER_TIMEOUT_S
    future = _RELAYER_EXECUTOR.submit(relayer_submitter, payload)
    try:
        return future.result(timeout=effective_timeout)
    except FuturesTimeoutError as exc:
        raise TransferError(
            "relayer_timeout",
            f"relayer call exceeded {effective_timeout}s",
        ) from exc


logger = logging.getLogger(__name__)


_PREVIEW_TTL_S: int = 300  # 5 minutes per D-LIVE-21


